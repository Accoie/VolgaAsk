from ..errors import ProviderError
from ..llm.base import BaseLLMProvider


class DialogInterpreter:
    def __init__(self, provider: BaseLLMProvider):
        """Подключает модель понимания реплик."""
        self.provider = provider

    def interpret(self, message: str, context: str) -> dict:
        """Определяет намерение и готовит уточнение."""
        actions = ["confirm", "reject", "cancel", "data", "question", "unclear"]
        schema = {
            "type": "object",
            "properties": {
                "action": {"type": "string", "enum": actions},
                "reply": {"type": "string"},
                "value": {"type": ["string", "null"]},
            },
            "required": ["action", "reply", "value"],
            "additionalProperties": False,
        }
        instruction = (
            "Ты помощник по заполнению заявления. Определи намерение реплики по контексту. "
            "confirm — явное согласие продолжить или разрешение создать документ. "
            "На этапе предложения «давай» — confirm. После сводки фразы "
            "«всё правильно, можешь создавать» и «можно оформлять» — confirm. "
            "Повелительная форма и разрешение создать файл считаются подтверждением. "
            "Для confirm верни пустой reply и null в value. reject — отказ от предложения. "
            "cancel — только явная просьба полностью завершить сессию, например «отмени всё». "
            "Отказ продолжать на этапе предложения (например «пока не хочу») — reject. "
            "data — ответ на текущий вопрос или исправление. "
            "Если пользователь сообщает несколько полей заявления сразу, выбери data, "
            "даже если часть значений не относится к текущему вопросу. "
            "Например «Группа АБ-12, факультет ФИиВТ, ФИО Иванов Иван Иванович» — data. "
            "question — вопрос пользователя. unclear — непонятная реплика. "
            "Согласие с оговоркой или просьбой исправить данные не является confirm. "
            "Если есть сомнение в согласии, выбери unclear. "
            "В value дословно скопируй ответ на текущее поле, иначе null. "
            "Короткие разговорные ответы вроде «справочка» допустимы как название документа "
            "и относятся к data. Регистр букв не влияет на допустимость ответа. "
            "Проверяй смысл короткого ответа по текущему полю. "
            "Для названия документа «СПРАВОЧКА» — data, value «СПРАВОЧКА», "
            "а «ФЫОАЫВАФВ» или одиночная буква — unclear, value null. "
            "Не переносить непонятные слова в поля только потому, что поле текстовое. "
            "В reply кратко ответь на вопрос или попроси пояснить непонятную реплику, "
            "опираясь на контекст. Не выдумывай данные и требования к документу. "
            "Только приложение сообщает об изменении данных или создании файла. "
            "В остальных случаях верни пустой reply. Контекст: " + context
        )
        result = self.provider.request_json(instruction, message, schema)
        if result.get("action") not in actions or not isinstance(result.get("reply"), str):
            raise ProviderError("Не удалось понять ответ. Переформулируй, пожалуйста.")
        return result
